"""The information a revision plan needs ('slots'), and how each one is asked for.

Questions are fixed text written by the designer, not generated by the model,
so that Condition A (open) and Condition B (options + custom) ask for the same
missing information in the same order (A1: same tasks, same information).
"""
from __future__ import annotations

import random
from datetime import date, timedelta

# Order matters: it is the order the ask policy works through missing slots.
SLOT_ORDER = ["exam_date", "subjects", "daily_hours", "priority_subject", "constraints"]
REQUIRED = {"exam_date", "subjects"}          # no plan without these
LABELS = {
    "exam_date": "First exam date",
    "subjects": "Subjects to revise",
    "daily_hours": "Study time per day",
    "priority_subject": "Subject that needs most work",
    "constraints": "Constraints",
}

QUESTIONS = {
    "exam_date": {
        "ask": "When is your first exam?",
        "clarify": "I couldn't pin down the exam date. Which day is your first exam?",
    },
    "subjects": {
        "ask": "Which subjects do you need to revise?",
        "clarify": "I'm not sure which subjects you mean. Which subjects should the plan cover?",
    },
    "daily_hours": {
        "ask": "How many hours can you study each day?",
        "clarify": "Roughly how many hours a day is that? A number helps me fit the plan.",
    },
    "priority_subject": {
        "ask": "Which subject needs the most work?",
        "clarify": "Which one of your subjects should get the most time?",
    },
    "constraints": {
        "ask": "Is there any time you can't study (for example weekends, or evenings only)?",
        "clarify": "When exactly can't you study?",
    },
}

# One short reason per question, shown under it in both conditions: says why the
# detail changes the plan (explain why, Amershi et al. G11; focused questions, Rahmani et al.).
WHY = {
    "exam_date": "Your first exam date sets how many days the plan covers.",
    "subjects": "The plan splits your time between these subjects.",
    "daily_hours": "This caps how much study I put into each day.",
    "priority_subject": "That subject will get the most time.",
    "constraints": "I'll keep those times free in the plan.",
}

COMMON_SUBJECTS =["Maths", "Physics", "Chemistry", "Biology", "Computer Science",
                   "English", "History", "Economics"]


def empty_slots() -> dict:
    return {name: {"value": None, "status": "missing", "source": None,
                   "evidence": None, "note": None} for name in SLOT_ORDER}


def question_text(slot: str, kind: str) -> str:
    return QUESTIONS[slot]["clarify" if kind == "clarify" else "ask"]


def options_for(slot: str, today: date, slots: dict, rng: random.Random) -> dict:
    """Options shown in Condition B. Every option set ends with a free 'Other'
    field in the UI, so options never limit what the student can say.

    Returns {"multi": bool, "options": [(label, value), ...]}.
    """
    if slot == "exam_date":
        # Chronological order: the layout maps onto the calendar (Lecture 06, mapping).
        days = [today + timedelta(days=i) for i in range(1, 15)]
        return {"multi": False,
                "options": [(d.strftime("%a %d %b"), d.isoformat()) for d in days]}
    if slot == "subjects":
        mentioned = slots["subjects"]["value"] or []
        pool = [s for s in COMMON_SUBJECTS if s not in mentioned]
        rng.shuffle(pool)  # shuffled to reduce order/anchoring effects (Lecture 06)
        return {"multi": True, "options": [(s, s) for s in mentioned + pool]}
    if slot == "daily_hours":
        return {"multi": False,
                "options": [("1 h", 1), ("2 h", 2), ("3 h", 3), ("4 h", 4), ("5 h", 5), ("6 h", 6)]}
    if slot == "priority_subject":
        subjects = list(slots["subjects"]["value"] or [])
        rng.shuffle(subjects)
        return {"multi": False,
                "options": [(s, s) for s in subjects] + [("All about the same", "none")]}
    if slot == "constraints":
        return {"multi": False, "options": [
            ("No constraints", "none"),
            ("Weekends off", "No study on Saturdays or Sundays"),
            ("Evenings only", "Can only study in the evenings"),
        ]}
    raise KeyError(slot)
